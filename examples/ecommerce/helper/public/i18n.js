export function normalizeLanguage(language = "en") {
  return /^zh(?:[-_]|$)/i.test(String(language).split(/[,;.]/)[0]) ? "zh" : "en";
}
export function translate(language, key, values = {}) {
  const text = normalizeLanguage(language) === "zh" ? key : (english[key] || key);
  return text.replace(/\{(\w+)\}/g, (match, name) => String(values[name] ?? match));
}
export function applyTranslations(root, language) {
  root.documentElement?.setAttribute("lang", language === "zh" ? "zh-CN" : "en");
  for (const node of root.querySelectorAll("[data-i18n]")) {
    node.textContent = translate(language, node.dataset.i18n, JSON.parse(node.dataset.i18nValues || "{}"));
  }
  for (const attribute of ["title", "aria-label", "placeholder"]) {
    for (const node of root.querySelectorAll(`[data-i18n-${attribute}]`)) {
      node.setAttribute(attribute, translate(language, node.getAttribute(`data-i18n-${attribute}`)));
    }
  }
}
export function setTranslatedText(node, language, key, values = {}) {
  node.dataset.i18n = key;
  node.dataset.i18nValues = JSON.stringify(values);
  node.textContent = translate(language, key, values);
}
